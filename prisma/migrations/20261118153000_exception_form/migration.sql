-- The daily exception entry is a form. Exceptions are the problems that form produces.

CREATE TABLE exception_forms (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code varchar(40) NOT NULL UNIQUE,
  name varchar(120) NOT NULL,
  active boolean NOT NULL DEFAULT true
);

CREATE TABLE exception_form_fields (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  form_id integer NOT NULL REFERENCES exception_forms (id) ON DELETE CASCADE,
  line_no smallint NOT NULL,
  field_no smallint NOT NULL,
  field_key varchar(40) NOT NULL,
  value_key varchar(40),
  label varchar(500) NOT NULL,
  kind varchar(16) NOT NULL,
  parent_key varchar(40),
  raises_exception boolean NOT NULL DEFAULT false,
  incident boolean NOT NULL DEFAULT false,
  unit varchar(40),
  decimals smallint,
  options jsonb,
  min_tanks smallint,
  sort_order integer NOT NULL,
  CONSTRAINT exception_form_fields_kind CHECK (kind IN ('yes_no', 'text', 'count', 'decimal', 'select')),
  CONSTRAINT exception_form_fields_key UNIQUE (form_id, field_key)
);

CREATE TABLE form_exceptions (
  daily_exception_id uuid NOT NULL REFERENCES daily_exceptions (id) ON DELETE CASCADE,
  field_key varchar(40) NOT NULL,
  line_no smallint NOT NULL,
  summary varchar(500) NOT NULL,
  PRIMARY KEY (daily_exception_id, field_key)
);

INSERT INTO exception_forms (code, name) VALUES ('DAILY', 'Daily Exception');

INSERT INTO exception_form_fields
  (form_id, line_no, field_no, field_key, value_key, label, kind, parent_key, raises_exception, incident, sort_order)
SELECT f.id, q.line_no, q.answer_no, 'l' || q.line_no, NULL, q.question, 'yes_no', NULL, true, q.incident, q.line_no * 100
FROM exception_questions q
CROSS JOIN exception_forms f
WHERE f.code = 'DAILY';

INSERT INTO exception_form_fields
  (form_id, line_no, field_no, field_key, value_key, label, kind, parent_key, raises_exception, incident, unit, decimals, options, min_tanks, sort_order)
SELECT f.id, q.line_no, d.field_no, 'l' || q.line_no || '_' || d.field_key, d.field_key, d.label, d.kind,
       'l' || q.line_no, false, false, d.unit, d.decimals, d.options, d.min_tanks, q.line_no * 100 + d.sort_order
FROM exception_question_fields d
JOIN exception_questions q ON q.id = d.question_id
CROSS JOIN exception_forms f
WHERE f.code = 'DAILY';

-- Problems already sitting on submitted forms.
INSERT INTO form_exceptions (daily_exception_id, field_key, line_no, summary)
SELECT e.id, 'l' || l.line_no, l.line_no,
  LEFT(COALESCE(NULLIF(l.details ->> 'remarks', ''), q.question), 500)
FROM daily_exceptions e
JOIN daily_exception_lines l ON l.exception_id = e.id AND l.answer = 'YES'
JOIN exception_questions q ON q.line_no = l.line_no
WHERE e.status = 'PENDING';

INSERT INTO form_exceptions (daily_exception_id, field_key, line_no, summary)
SELECT e.id, 'plant_status', 0, 'Plant non-operational'
FROM daily_exceptions e
WHERE e.status = 'PENDING'
  AND e.plant_status = 'NON_OPERATIONAL'
  AND NOT EXISTS (
    SELECT 1 FROM daily_exception_lines l
    WHERE l.exception_id = e.id AND l.answer = 'YES'
  );

DROP TABLE exception_question_fields;
DROP TABLE exception_questions;

ALTER TABLE exception_forms ENABLE ROW LEVEL SECURITY;
ALTER TABLE exception_form_fields ENABLE ROW LEVEL SECURITY;
ALTER TABLE form_exceptions ENABLE ROW LEVEL SECURITY;

CREATE POLICY exception_forms_read ON exception_forms
  FOR SELECT USING (app_current_user_id() IS NOT NULL);
CREATE POLICY exception_forms_write ON exception_forms
  FOR ALL USING (app_is_admin()) WITH CHECK (app_is_admin());

CREATE POLICY exception_form_fields_read ON exception_form_fields
  FOR SELECT USING (EXISTS (SELECT 1 FROM exception_forms f WHERE f.id = form_id));
CREATE POLICY exception_form_fields_write ON exception_form_fields
  FOR ALL USING (app_is_admin()) WITH CHECK (app_is_admin());

CREATE POLICY form_exceptions_read ON form_exceptions
  FOR SELECT USING (
    EXISTS (SELECT 1 FROM daily_exceptions d WHERE d.id = daily_exception_id)
  );
CREATE POLICY form_exceptions_write ON form_exceptions
  FOR ALL USING (
    EXISTS (SELECT 1 FROM daily_exceptions d WHERE d.id = daily_exception_id)
  )
  WITH CHECK (
    EXISTS (SELECT 1 FROM daily_exceptions d WHERE d.id = daily_exception_id)
  );
