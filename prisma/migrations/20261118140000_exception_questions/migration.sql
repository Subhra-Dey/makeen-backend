ALTER TABLE exception_questions ENABLE ROW LEVEL SECURITY;
ALTER TABLE exception_question_fields ENABLE ROW LEVEL SECURITY;

CREATE POLICY exception_questions_read ON exception_questions
  FOR SELECT USING (app_current_user_id() IS NOT NULL);
CREATE POLICY exception_questions_write ON exception_questions
  FOR ALL USING (app_is_admin()) WITH CHECK (app_is_admin());

CREATE POLICY exception_question_fields_read ON exception_question_fields
  FOR SELECT USING (
    EXISTS (SELECT 1 FROM exception_questions q WHERE q.id = question_id)
  );
CREATE POLICY exception_question_fields_write ON exception_question_fields
  FOR ALL USING (app_is_admin()) WITH CHECK (app_is_admin());
