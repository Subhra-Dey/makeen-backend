-- Daily Exception checklist lives in the database. The form and the save rules read these rows.

CREATE TABLE exception_questions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  line_no smallint NOT NULL UNIQUE,
  answer_no smallint NOT NULL,
  question varchar(500) NOT NULL,
  incident boolean NOT NULL DEFAULT false,
  active boolean NOT NULL DEFAULT true
);

CREATE TABLE exception_question_fields (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question_id integer NOT NULL REFERENCES exception_questions (id) ON DELETE CASCADE,
  field_key varchar(40) NOT NULL,
  field_no smallint NOT NULL,
  label varchar(200) NOT NULL,
  kind varchar(16) NOT NULL,
  unit varchar(40),
  decimals smallint,
  options jsonb,
  min_tanks smallint,
  sort_order integer NOT NULL,
  CONSTRAINT exception_question_fields_kind CHECK (kind IN ('text', 'count', 'decimal', 'select')),
  CONSTRAINT exception_question_fields_key UNIQUE (question_id, field_key)
);

